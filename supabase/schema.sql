-- 1. Criação da tabela principal de leituras de telemetria
CREATE TABLE IF NOT EXISTS public.telemetry_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,                  -- Identificação do dispositivo (ex: esp32-rack-ia-01)
    metric TEXT NOT NULL,                     -- Grandeza medida (ex: temperatura_rack_gpu)
    value NUMERIC(6, 2) NOT NULL,             -- Valor tratado no ESP32 (média móvel)
    raw_value NUMERIC(6, 2),                  -- Valor bruto lido do sensor DHT22
    humidity NUMERIC(5, 2),                   -- Umidade relativa do corredor do Rack (%)
    unit TEXT NOT NULL DEFAULT '°C',          -- Unidade de medida
    threshold NUMERIC(6, 2) NOT NULL DEFAULT 30.00, -- Limite térmico configurado para alerta (30 °C)
    alert BOOLEAN NOT NULL DEFAULT FALSE,     -- Condição de alerta (true quando value > threshold)
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW() -- Horário exato do recebimento/armazenamento
);

-- 2. Índices para acelerar a busca da leitura mais recente e do histórico por dispositivo
CREATE INDEX IF NOT EXISTS idx_telemetry_created_at
    ON public.telemetry_readings (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_telemetry_device_metric
    ON public.telemetry_readings (device_id, metric, created_at DESC);

-- 3. Habilitação de Row Level Security (RLS)
ALTER TABLE public.telemetry_readings ENABLE ROW LEVEL SECURITY;

-- Política de leitura pública para consulta via API REST / Painel Frontend
DROP POLICY IF EXISTS "Permitir leitura de telemetria" ON public.telemetry_readings;
CREATE POLICY "Permitir leitura de telemetria"
    ON public.telemetry_readings
    FOR SELECT
    USING (true);

-- Política de inserção via Edge Function (Service Role ou Anon configurada no projeto)
DROP POLICY IF EXISTS "Permitir insercao de telemetria pelo ESP32" ON public.telemetry_readings;
CREATE POLICY "Permitir insercao de telemetria pelo ESP32"
    ON public.telemetry_readings
    FOR INSERT
    WITH CHECK (true);

-- 4. Permissões de acesso à tabela e sequência para a API do Supabase
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.telemetry_readings TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

